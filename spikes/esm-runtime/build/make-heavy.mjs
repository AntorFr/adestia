// Generates plugins/hello/heavy-data.js (~450 kB) to make the lazy chunk
// realistically heavy (the predecessor's scan decoder was ~450 kB).
// This is PLUGIN-INTERNAL pre-generated data, not shell bundling.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'plugins', 'hello', 'heavy-data.js');

const chunk = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
let data = '';
while (data.length < 450_000) data += chunk;

const src = `// GENERATED by build/make-heavy.mjs — do not edit.
export const SAMPLE = ${JSON.stringify(data.slice(0, 64))};
export const PAYLOAD = ${JSON.stringify(data)};
export const PAYLOAD_BYTES = ${data.length};
`;
writeFileSync(out, src);
console.log(`wrote ${out} (${src.length} bytes)`);
