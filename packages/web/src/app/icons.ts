/** The closed list: a name outside it does not compile. */
export type IconName = keyof typeof ICON_PATHS

export const ICON_NAMES = Object.keys(ICON_PATHS) as IconName[]

const SPRITE_ID = 'adestia-icon-sprite'

/** The id a `<use href>` points at. */
export function iconId(name: IconName): string {
  return `adestia-i-${name}`
}

/** The hidden sprite as markup: one `<symbol>` per icon. */
export function spriteMarkup(): string {
  const symbols = ICON_NAMES.map((n) => `<symbol id="${iconId(n)}" viewBox="0 0 24 24">${ICON_PATHS[n]}</symbol>`)
  return `<svg id="${SPRITE_ID}" xmlns="http://www.w3.org/2000/svg" aria-hidden="true" width="0" height="0" style="position:absolute;width:0;height:0;overflow:hidden">${symbols.join('')}</svg>`
}

/** Mount the sprite once; calling it again is a no-op. */
export function mountSprite(doc: Document = document): void {
  if (doc.getElementById(SPRITE_ID)) return
  const host = doc.createElement('div')
  host.innerHTML = spriteMarkup()
  doc.body.prepend(host.firstElementChild as Element)
}
