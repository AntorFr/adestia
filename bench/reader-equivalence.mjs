#!/usr/bin/env node
/**
 * Compare the reader's DOM with a prior revision on the core-blocks and blocks
 * markdown seeds, with and without a page/index and with file requests settled.
 *
 *   node bench/reader-equivalence.mjs <baseline-ref>
 *
 * Uses the repository's Vitest/jsdom setup. Only temporary files are written;
 * the baseline reader resolves the unchanged helpers beside the current one.
 * Existing test files and their assertions are never changed.
 */
import { execFileSync } from 'node:child_process'
import { randomUUID } from 'node:crypto'
import { writeFileSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const baseline = process.argv[2]
if (!baseline) {
  console.error('usage: node bench/reader-equivalence.mjs <baseline-ref>')
  process.exit(2)
}
const id = randomUUID()
const reader = join(root, 'packages/web/src/editor', 'Reader.before-' + id + '.tsx')
const test = join(root, 'packages/web/test', 'reader-equivalence-' + id + '.test.tsx')
const proof = String.raw`// @vitest-environment jsdom
// Generated by bench/reader-equivalence.mjs; removed after the rendering proof.
import { readFileSync } from 'node:fs'
import ts from 'typescript'
import { act, cleanup, render } from '@testing-library/react'
import { expect, it } from 'vitest'
import { registerBlocks, forgetContributedBlocks } from '@antorfr/adestia-content'
import { Reader } from '../src/editor/Reader.js'
import { Reader as Before } from '../src/editor/Reader.before.js'

it('keeps the innerHTML of the core-blocks and blocks corpus', async () => {
  const seeds = new Set<string>()
  for (const file of ['core-blocks', 'blocks']) {
    const source = ts.createSourceFile(file + '.tsx', readFileSync('packages/web/test/' + file + '.test.tsx', 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
    const visit = (node: ts.Node) => {
      if ((ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) && node.text.includes(':::')) seeds.add(node.text)
      ts.forEachChild(node, visit)
    }
    visit(source)
  }
  registerBlocks({ note: { content: 'empty', description: 'A note.' }, parcours: { content: 'empty', description: 'A walk.', attributes: { source: { required: true } } }, custom: { content: 'flow', description: 'Prose.' } }, { plugin: 'demo', kind: 'feature' })
  const pages = [
    { path: 'chantiers/adestia/socle.md', fields: { title: 'Socle de contenu', status: 'en cours', type: 'chantier' }, blocks: { etat: 'Huit lots sur treize ; le parseur tient.', perimetre: 'Hors infra.' } },
    { path: 'chantiers/adestia/tours.md', fields: { title: 'Les tours', status: 'clos', ico: '🌀' } },
    { path: 'chantiers/adestia/INDEX.md', fields: { title: 'Adestia' } },
  ]
  const files = [{ path: 'chantiers/adestia/assets/photo.png', name: 'photo.png', bytes: 1024, kind: 'image', modified: '2026-10-17' }, { path: 'chantiers/adestia/plan.pdf', name: 'plan.pdf', bytes: 4000, kind: 'pdf', modified: '2026-10-16' }]
  let checks = 0
  for (const markdown of seeds) {
    for (const context of [false, true]) {
      const props = { markdown, ...(context ? { path: 'chantiers/adestia/INDEX.md', store: 'famille', fields: { type: 'chantier' }, pages } : {}), fetchImpl: (async () => new Response(JSON.stringify({ files }))) as typeof fetch, blocks: { demo: { note: () => <i>Note</i>, parcours: () => <b>Walk</b>, custom: ({ children }: { children?: React.ReactNode }) => <aside>{children}</aside> } } }
      const old = render(<Before {...props} />)
      await act(async () => {})
      const expected = old.container.innerHTML
      cleanup()
      const next = render(<Reader {...props} />)
      await act(async () => {})
      expect(next.container.innerHTML, markdown).toBe(expected)
      cleanup()
      checks++
    }
  }
  forgetContributedBlocks()
  console.log(seeds.size + ' markdown seeds; ' + checks + ' identical innerHTML comparisons')
})
`
try {
  const source = execFileSync('git', ['show', baseline + ':packages/web/src/editor/Reader.tsx'], { cwd: root, encoding: 'utf8' })
  writeFileSync(reader, source)
  writeFileSync(test, proof.replace('Reader.before.js', 'Reader.before-' + id + '.js'))
  execFileSync(process.execPath, [join(root, 'node_modules/vitest/vitest.mjs'), 'run', test], { cwd: root, stdio: 'inherit' })
} catch (error) {
  if (error.status === undefined) console.error(error.message)
  process.exitCode = 1
} finally {
  rmSync(reader, { force: true })
  rmSync(test, { force: true })
}
